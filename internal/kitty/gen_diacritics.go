//go:build ignore

// gen_diacritics writes diacritics_table.go from kitty's list of the
// combining characters that encode row/column numbers in Unicode placeholders:
//
//	curl -LO https://raw.githubusercontent.com/kovidgoyal/kitty/master/gen/rowcolumn-diacritics.txt
//	go run gen_diacritics.go rowcolumn-diacritics.txt
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"strconv"
	"strings"
)

func main() {
	f, err := os.Open(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	var b bytes.Buffer
	b.WriteString("// Code generated by gen_diacritics.go from kitty's rowcolumn-diacritics.txt; DO NOT EDIT.\n\npackage kitty\n\n")
	b.WriteString("// diacritics[n] encodes the number n in a placeholder cell.\nvar diacritics = []rune{")
	n := 0
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		cp, _, _ := strings.Cut(line, ";")
		r, err := strconv.ParseUint(cp, 16, 32)
		if err != nil {
			log.Fatal(err)
		}
		if n%8 == 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "0x%04X, ", r)
		n++
	}
	b.WriteString("\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("diacritics_table.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %d diacritics\n", n)
}
