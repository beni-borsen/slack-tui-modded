//go:build ignore

// gen_emoji writes emoji_table.go from iamcal/emoji-data, the dataset Slack's
// shortcodes come from:
//
//	curl -LO https://raw.githubusercontent.com/iamcal/emoji-data/v16.0.0/emoji.json
//	go run gen_emoji.go emoji.json
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"os"
	"slices"
	"strconv"
	"strings"
)

func main() {
	if len(os.Args) != 2 {
		log.Fatal("usage: go run gen_emoji.go emoji.json")
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		log.Fatal(err)
	}
	var data []struct {
		Unified    string   `json:"unified"`
		ShortNames []string `json:"short_names"`
	}
	if err := json.Unmarshal(raw, &data); err != nil {
		log.Fatal(err)
	}
	table := map[string]string{}
	for _, e := range data {
		var sb strings.Builder
		for _, cp := range strings.Split(e.Unified, "-") {
			r, err := strconv.ParseUint(cp, 16, 32)
			if err != nil {
				log.Fatalf("%s: %v", e.Unified, err)
			}
			sb.WriteRune(rune(r))
		}
		for _, n := range e.ShortNames {
			table[n] = sb.String()
		}
	}
	names := make([]string, 0, len(table))
	for n := range table {
		names = append(names, n)
	}
	slices.Sort(names)

	var b bytes.Buffer
	b.WriteString("// Code generated by gen_emoji.go from iamcal/emoji-data v16.0.0; DO NOT EDIT.\n\npackage render\n\n")
	b.WriteString("var emojiTable = map[string]string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %+q,\n", n, table[n])
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("emoji_table.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Printf("wrote %d shortcodes\n", len(names))
}
