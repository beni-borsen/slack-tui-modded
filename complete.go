// bashCompletion is installed as
// ~/.local/share/bash-completion/completions/slack and asks
// `slack __complete` for suggestions for the first argument (the target).
const bashCompletion = `# bash completion for slack (slack-tui). Generated by: slack completion bash
_slack() {
	local cur=${COMP_WORDS[COMP_CWORD]} target=1
	case ${COMP_WORDS[1]} in -n|--dry-run) target=2 ;; esac
	(( COMP_CWORD == 1 || COMP_CWORD == target )) || return 0
	local IFS=$'\n'
	COMPREPLY=($(command slack __complete "$cur" 2>/dev/null))
}
complete -o nosort -F _slack slack
`

var subcommands = []string{"login", "logout", "doctor", "completion", "-n"}

// completeWord prints suggestions for word, one per line, from the local
// names cache. A stale or missing cache is refreshed in the background so
// the next TAB has it; this one answers with what there is.
func completeWord(word string) {
	c, ok := names.Load()
	if !ok || time.Since(c.Updated) > names.MaxAge {
		refreshInBackground()
	}
	for _, s := range candidates(c, word) {
		fmt.Println(s)
	}
}

func candidates(c names.Cache, word string) []string {
	if q, ok := strings.CutPrefix(word, "@"); ok {
		return peopleCandidates(c.People, q)
	}
	q := strings.ToLower(word)
	var out []string
	for _, s := range subcommands {
		if strings.HasPrefix(s, q) && q != "" {
			out = append(out, s)
		}
	}
	var chans []string
	for _, ch := range c.Channels {
		if strings.HasPrefix(strings.ToLower(ch), q) || wordPrefix(strings.ToLower(ch), q) {
			chans = append(chans, ch)
		}
	}
	slices.Sort(chans)
	return append(out, chans...)
}

var shellSafe = regexp.MustCompile(`^[\p{L}\p{N}._\-]+$`)

// peopleCandidates suggests "@name" for everyone matching q: the name
// Slack shows for them when it's one shell-safe word that no one else
// shares, otherwise their username. Either resolves to exactly that person when sent.
func peopleCandidates(people []names.Person, q string) []string {
	q = strings.ToLower(q)
	// How many people go by each name (a person counts once, even when
	// their display name and full name are the same).
	taken := map[string]int{}
	for _, p := range people {
		mine := map[string]bool{}
		for _, n := range []string{p.DisplayName, p.RealName, p.Name} {
			if n != "" {
				mine[strings.ToLower(n)] = true
			}
		}
		for n := range mine {
			taken[n]++
		}
	}
	var starts, others []string
	for _, p := range people {
		match := false
		for _, n := range []string{p.DisplayName, p.RealName, p.Name} {
			if n != "" && (strings.HasPrefix(strings.ToLower(n), q) || wordPrefix(strings.ToLower(n), q)) {
				match = true
			}
		}
		if !match {
			continue
		}
		tok := p.Name
		// The name Slack shows: display name, else full name.
		shown := p.DisplayName
		if shown == "" {
			shown = p.RealName
		}
		if shown != "" && shellSafe.MatchString(shown) && taken[strings.ToLower(shown)] == 1 {
			tok = shown
		}
		if strings.HasPrefix(strings.ToLower(tok), q) {
			starts = append(starts, "@"+tok)
		} else {
			others = append(others, "@"+tok)
		}
	}
	slices.Sort(starts)
	slices.Sort(others)
	// bash puts the longest common prefix of several suggestions in place
	// of the word; suggestions that start with what was typed keep it intact.
	if len(starts) > 0 && len(starts)+len(others) > 1 {
		return starts
	}
	return append(starts, others...)
}

// refreshInBackground starts `slack __refresh-names` detached, at most
// once every two minutes.
func refreshInBackground() {
	marker := filepath.Join(cacheDir(), "names.refreshing")
	if st, err := os.Stat(marker); err == nil && time.Since(st.ModTime()) < 2*time.Minute {
		return
	}
	os.MkdirAll(filepath.Dir(marker), 0o700)
	os.WriteFile(marker, nil, 0o600)
	exe, err := os.Executable()
	if err != nil {
		return
	}
	cmd := exec.Command(exe, "__refresh-names")
	cmd.SysProcAttr = &syscall.SysProcAttr{Setsid: true}
	if cmd.Start() == nil {
		go cmd.Process.Release()
	}
}

func refreshNames() error {
	tokens, err := auth.Load()
	if err != nil {
		return err
	}
	ctx, cancel := context.WithTimeout(context.Background(), time.Minute)
	defer cancel()
	c := backend.New(tokens)
	users, err := c.Users(ctx)
	if err != nil {
		return err
	}
	convs, err := c.Conversations(ctx)
	if err != nil {
		return err
	}
	return names.Save(users, convs)
}

func cacheDir() string {
	if d := os.Getenv("XDG_CACHE_HOME"); d != "" {
		return filepath.Join(d, "slack-tui")
	}
	home, _ := os.UserHomeDir()
	return filepath.Join(home, ".cache", "slack-tui")
}
